    private void bookData(){
        try {
            int QQ;
            
            pst = con.prepareStatement("SELECT * FROM book");
            
            ResultSet Rs = pst.executeQuery();
            
            ResultSetMetaData RSMD = Rs.getMetaData();
            
            QQ = RSMD.getColumnCount();
            
            DefaultTableModel DFG = (DefaultTableModel)jTable1.getModel();
            DFG.setRowCount(0);
            
            while(Rs.next()){
                
                Vector v2 = new Vector();
                
                for(int aa = 1; aa <=QQ; aa++){
                    
                    v2.add(Rs.getString("acquisition_no"));
                    v2.add(Rs.getString("title"));
                    v2.add(Rs.getString("author"));
                    v2.add(Rs.getString("date_published"));
                    v2.add(Rs.getString("category"));
                    v2.add(Rs.getString("status"));
                }
                DFG.addRow(v2);
            }
            int rowCount = DFG.getRowCount();
            txttotalbook.setText(String.valueOf(rowCount));
            
        } catch (SQLException ex) {
            System.getLogger(book.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

