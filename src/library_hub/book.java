    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndeleteActionPerformed
            int row = jTable1.getSelectedRow();
    
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a book from the table!");
        return;
    }

    // Get the specific ID from the selected row (Column 0 is Acq Number)
    String idToDelete = jTable1.getValueAt(row, 0).toString();

    int dialogResult = JOptionPane.showConfirmDialog(null, "Do you want to Delete this record?", "Warning", JOptionPane.YES_NO_OPTION);
    if (dialogResult == JOptionPane.YES_OPTION) {
        try {
            // Target ONLY this specific acquisition number
            pst = con.prepareStatement("DELETE FROM book WHERE acquisition_no = ? LIMIT 1");
            pst.setString(1, idToDelete);
            pst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Record Deleted Successfully");
            
            // Refresh the table and clear fields
            updateTable();
            setDefault(); 
            
        } catch (SQLException ex) {
            Logger.getLogger(book.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    }//GEN-LAST:event_btndeleteActionPerformed

