    private void searchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchKeyReleased
        // TODO add your handling code here:
        String uname = search.getText();

    // Use a parameterized query to prevent SQL Injection
    String query = "SELECT * FROM book WHERE title LIKE ? OR category LIKE ? OR author LIKE ?";

    try {
        Connection con = MySQLConnect.getConnection();
        PreparedStatement pst = con.prepareStatement(query);

        // Prepare the search pattern (e.g., %searchTerm%)
       String searchPattern = "%" + uname + "%";

        // Set parameters (JDBC starts at index 1)
        pst.setString(1, searchPattern);
        pst.setString(2, searchPattern); 
        pst.setString(3, searchPattern); 

        ResultSet rs = pst.executeQuery(); // Note: No 'query' string inside parentheses here

        DefaultTableModel tblModel = (DefaultTableModel) jTable1.getModel();
        tblModel.setRowCount(0); // Clear existing rows

        while (rs.next()) {
            Vector<String> colData = new Vector<>();
            colData.add(rs.getString("acquisition_no"));
            colData.add(rs.getString("title"));
            colData.add(rs.getString("author"));
            colData.add(rs.getString("date_published"));
            colData.add(rs.getString("category"));
            colData.add(rs.getString("status"));

            tblModel.addRow(colData);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Database Error: " + e.getMessage());
    }
    }//GEN-LAST:event_searchKeyReleased

